def _dedupe_by_title(rows):
    """`(title, category)` の list から title 重複を除去 (最初の出現保持)。"""
    seen = set()
    result = []
    for title, category in rows:
        if title not in seen:
            seen.add(title)
            result.append((title, category))
    return result


